import { kitRoles } from "../src/themes/kit";
import terminalPalettes from "../src/themes/terminal-palettes.json";
import { readFileSync, writeFileSync } from "node:fs";
import { themeTokens } from "../src/themes/index";
import codesense from "../src/themes/codesense.tokens.json";
import { aliasCss } from "../src/themes/css";
import { format, resolveConfig } from "prettier";

const block = (selector: string, entries: Record<string, string>) =>
  `${selector} {\n${Object.entries(entries)
    .map(([k, v]) => `  ${k}: ${v};`)
    .join("\n")}\n}\n`;
const light = themeTokens("codesense", "light"),
  dark = themeTokens("codesense", "dark");
const banner = "/* Generated by pnpm gen:theme. Do not edit. */\n";
const appPath = "src/styles/theme-tokens.css";
const base = JSON.parse(
  readFileSync(new URL("../src/themes/kit-layout.json", import.meta.url), "utf8"),
);
const app = await format(
  banner + block(":root", { ...base, ...light }) + block(":root.dark", dark) + aliasCss(),
  {
    ...(await resolveConfig(appPath)),
    filepath: appPath,
  },
);
const lightAliases = kitRoles("viewer", (role) => `--theme-${role}` in light);
const darkAliases = kitRoles("viewer", (role) => `--theme-${role}` in dark);

const kit =
  banner +
  block(":root", {
    ...base,
    ...Object.fromEntries(
      Object.entries(lightAliases).map(([k, v]) => [
        `--cs-${k}`,
        `light-dark(${light[`--theme-${v}`]}, ${dark[`--theme-${darkAliases[k]}`]})`,
      ]),
    ),
  });
const terminalKitPath = "src-tauri/src/dashboard_publish/toolkit/cs-live.js";
const terminalKit = readFileSync(terminalKitPath, "utf8").replace(
  /(\/\/ cs-themes:begin\s*var THEMES = )(\{.*?\})(;\s*\/\/ cs-themes:end)/s,
  (_, head, _old, tail) =>
    head +
    JSON.stringify(
      Object.fromEntries(
        Object.entries(terminalPalettes).map(([id, config]) => [
          id,
          { chrome: config.chromeBg, ...config.theme },
        ]),
      ),
    ).replace(/</g, "\\u003c") +
    tail,
);
for (const [path, value] of [
  [appPath, app],
  ["src-tauri/src/http/routes/dashboard_kit/tokens.css", kit],
  [terminalKitPath, terminalKit],
  [
    "codesense-docs/getting-started/content/examples/themes/example.tokens.json",
    JSON.stringify({ ...codesense, id: "example", name: "Example" }, null, 2) + "\n",
  ],
]) {
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== value)
      throw new Error(`${path} is stale; run pnpm gen:theme`);
  } else writeFileSync(path, value);
}
