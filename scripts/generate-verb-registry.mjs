export function renderRegistry(specs) {
  const source = readFileSync(resolve(root, "src-tauri/src/verbs/capabilities.rs"), "utf8");
  const values = (name) =>
    JSON.parse(
      "[" +
        source
          .match(new RegExp(`pub const ${name}:.*?= &\\[([\\s\\S]*?)\\];`))[1]
          .replace(/,\s*$/, "") +
        "]",
    );
  const all = values("ALL"),
    excluded = values("TEAM_EXCLUDED");
  const ceilings = {
    "right-pane": all,
    "file-nav": all,
    dock: all.filter((cap) => !excluded.includes(cap)),
  };
  const header = "// Generated by pnpm gen:verbs. Do not edit.\n";
  const registry = specs.map(
    ({
      name,
      class: cls,
      grant,
      inboxTarget,
      confirmable,
      action,
      mcpTwin,
      presentationOnlyReason,
    }) => ({
      name,
      class: cls,
      grant,
      inboxTarget,
      confirmable,
      action,
      mcpTwin,
      presentationOnlyReason,
    }),
  );
  const template = readFileSync(resolve(root, "scripts/codesense-sdk.d.ts.tmpl"), "utf8");
  const features = strArrayConst(
    readFileSync(resolve(root, "src-tauri/src/http/routes/viewer.rs"), "utf8"),
    "PAGE_SDK_FEATURES",
  );
  return {
    "src-tauri/src/http/routes/dashboard_kit/codesense.d.ts": renderSdk(specs, template),
    // Every verb is a method on window.codesense; a hand-written shim method of the same name wins.
    "src-tauri/src/http/routes/verb_methods.generated.js": `${header}(function(){var c=window.codesense;if(!c)return;${JSON.stringify(specs.map((s) => s.name))}.forEach(function(n){if(!(n in c))c[n]=function(a){return c.invoke(n,a||{})}})})();\n`,
    "src/features/dashboard/lib/verb-registry.generated.ts": `${header}export const VERB_REGISTRY = ${JSON.stringify(registry, null, 2)} as const;\nexport const SLOT_GRANT_CEILINGS = ${JSON.stringify(ceilings, null, 2)} as const;\nexport const PAGE_SDK_FEATURES = ${JSON.stringify(features, null, 2)} as const;\n`,
    "src/features/dashboard/lib/verb-names.generated.d.ts": `${header}export type PageVerbName = ${specs.map((s) => JSON.stringify(s.name)).join(" | ")};\n`,
    "codesense-docs/getting-started/content/generated/dashboard-verbs.generated.md":
      "# Dashboard verbs\n\nGenerated by `pnpm gen:verbs` from the Rust registry.\n\n| Verb | Class | Capability | Confirmable | MCP twin or presentation reason |\n| --- | --- | --- | --- | --- |\n" +
      specs
        .map(
          (s) =>
            `| ${s.name} | ${s.class} | ${s.grant} | ${s.confirmable ? "yes" : "no"} | ${s.mcpTwin ?? s.presentationOnlyReason} |`,
        )
        .join("\n") +
      "\n",
  };
}
const literal = (value) => JSON.stringify(value);
const member = (name) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : literal(name));
/** A JSON Schema as a TypeScript type. Generic schemas stay `Record<string, unknown>` / `unknown`. */
export function schemaType(schema, indent = "") {
  if (!schema || typeof schema !== "object") return "unknown";
  if ("const" in schema) return literal(schema.const);
  if (Array.isArray(schema.enum)) return schema.enum.map(literal).join(" | ");
  if (Array.isArray(schema.oneOf) && !schema.type)
    return schema.oneOf.map((part) => schemaType(part, indent)).join(" | ");
  if (Array.isArray(schema.type))
    return schema.type.map((type) => schemaType({ ...schema, type }, indent)).join(" | ");
  switch (schema.type) {
    case "string":
      return "string";
    case "number":
    case "integer":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array": {
      const item = schemaType(schema.items, indent);
      if (schema.minItems !== undefined && schema.minItems === schema.maxItems)
        return `[${Array(schema.minItems).fill(item).join(", ")}]`;
      return /[ |&]/.test(item) ? `Array<${item}>` : `${item}[]`;
    }
    case "object": {
      const entries = Object.entries(schema.properties ?? {});
      if (!entries.length) return "Record<string, unknown>";
      const required = new Set(schema.required ?? []);
      const inner = `${indent}  `;
      const lines = entries.map(
        ([key, value]) =>
          `${inner}${member(key)}${required.has(key) ? "" : "?"}: ${schemaType(value, inner)};`,
      );
      if (schema.additionalProperties !== false) lines.push(`${inner}[key: string]: unknown;`);
      return `{\n${lines.join("\n")}\n${indent}}`;
    }
    default:
      return "unknown";
  }
}
export function renderSdk(specs, template) {
  const methods = specs.map((s) => {
    const optional = !(s.argsSchema?.required ?? []).length;
    const notes = [
      s.class,
      s.grant,
      s.confirmable ? "confirmable" : null,
      s.mcpTwin ? `MCP twin ${s.mcpTwin}` : null,
    ];
    return `    /** ${notes.filter(Boolean).join(" · ")} */\n    ${member(s.name)}(args${optional ? "?" : ""}: ${schemaType(s.argsSchema, "    ")}): Promise<${schemaType(s.resultSchema, "    ")}>;`;
  });
  const block = `/** One method per registry verb: page args and result. */\n  interface VerbMethods {\n${methods.join("\n")}\n  }`;
  if (!template.includes("/* @generated-verb-methods */"))
    throw new Error("codesense-sdk.d.ts.tmpl lost its /* @generated-verb-methods */ marker");
  return template.replace("/* @generated-verb-methods */", block);
}
export function staleOutputs(outputs, read) {
  return Object.entries(outputs)
    .filter(([path, text]) => read(path) !== text)
    .map(([path]) => path);
}
