import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { test } from "node:test";

import {
  LICENCE_HEADER_EXEMPT,
  SPDX,
  UNLISTED,
  actionFor,
  addHeader,
  hasHeader,
  inScope,
  plan,
  skipReason,
  styleFor,
  summary,
} from "./spdx-headers.mjs";

test("the comment syntax follows the extension", () => {
  assert.equal(
    addHeader("fn main() {}\n", styleFor("src-tauri/src/main.rs")),
    `// ${SPDX}\nfn main() {}\n`,
  );
  assert.equal(addHeader("a { b: c }\n", styleFor("src/a.css")), `/* ${SPDX} */\na { b: c }\n`);
  assert.equal(addHeader("echo hi\n", styleFor("scripts/a.sh")), `# ${SPDX}\necho hi\n`);
  for (const shell of ["bash", "zsh", "fish"]) {
    const rel = `src-tauri/resources/shell-integration/codesense-shell-init.${shell}`;
    assert.ok(inScope(rel), rel);
    assert.equal(
      addHeader("# codesense shell integration\n", styleFor(rel)),
      `# ${SPDX}\n# codesense shell integration\n`,
    );
  }
  assert.equal(styleFor("src/a.json"), null);
  assert.equal(styleFor("src/.eslintrc"), null);
});

test("the header goes after a shebang, a Python coding line and a CSS @charset", () => {
  assert.equal(
    addHeader("#!/usr/bin/env bash\nset -e\n", "hash"),
    `#!/usr/bin/env bash\n# ${SPDX}\nset -e\n`,
  );
  assert.equal(
    addHeader("#!/usr/bin/env node\nrun();\n", "line"),
    `#!/usr/bin/env node\n// ${SPDX}\nrun();\n`,
  );
  assert.equal(
    addHeader("#!/usr/bin/env python3\n# -*- coding: utf-8 -*-\nx = 1\n", "hash"),
    `#!/usr/bin/env python3\n# -*- coding: utf-8 -*-\n# ${SPDX}\nx = 1\n`,
  );
  assert.equal(
    addHeader('@charset "utf-8";\na {}\n', "block"),
    `@charset "utf-8";\n/* ${SPDX} */\na {}\n`,
  );
  assert.equal(
    addHeader("#![allow(dead_code)]\nfn a() {}\n", "line"),
    `// ${SPDX}\n#![allow(dead_code)]\nfn a() {}\n`,
  );
});

test("line endings and a BOM are preserved, and a second run changes nothing", () => {
  assert.equal(addHeader("\uFEFFa();\r\nb();\r\n", "line"), `\uFEFF// ${SPDX}\r\na();\r\nb();\r\n`);
  const once = addHeader("a();", "line");
  assert.equal(once, `// ${SPDX}\na();`);
  assert.equal(addHeader(once, "line"), once);
  assert.ok(hasHeader(once));
});

