test("generated files and files with another licence header keep their bytes", () => {
  assert.equal(
    skipReason("/* Generated by pnpm gen:theme. Do not edit. */\n:root {}\n"),
    "generated",
  );
  assert.equal(skipReason("// @generated\nexport {};\n"), "generated");
  assert.equal(
    skipReason("/*! xterm.js | Copyright (c) 2017 The xterm.js authors | MIT License */\n"),
    "existing licence header",
  );
  assert.equal(
    skipReason("// SPDX-License-Identifier: Apache-2.0\nfn a() {}\n"),
    "existing licence header",
  );
  assert.equal(skipReason(""), "empty");
  assert.equal(
    skipReason("//! Seam tests: their generated files written for real.\nfn a() {}\n"),
    null,
  );
  assert.equal(skipReason("export const a = 1;\n"), null);
});

test("a licence header is a skip only for a listed file; any other fails the run", () => {
  const kit = [...LICENCE_HEADER_EXEMPT.keys()][0];
  assert.equal(kit, "src-tauri/src/http/routes/dashboard_kit/kit.js");
  const lucide = "/* Kit. Icons are Lucide (ISC License, Copyright (c) Lucide Icons). */\n";
  assert.equal(actionFor(kit, lucide), "existing licence header");
  assert.equal(actionFor("src/new.js", lucide), UNLISTED);
  assert.equal(actionFor("src/new.js", `// ${SPDX}\n${lucide}`), "ok");
  assert.equal(actionFor("src/gen.css", "/* Generated by x. Do not edit. */\n"), "generated");
  assert.equal(actionFor("src/a.ts", "a();\n"), "add");
  assert.equal(
    summary([{ action: "ok" }, { action: "add" }, { action: "ok" }, { action: UNLISTED }]),
    `add 1, ok 2, ${UNLISTED} 1`,
  );
});

test("plan reads tracked files only and reports each one's action", () => {
  const root = mkdtempSync(join(tmpdir(), "spdx-"));
  const put = (rel, text) => {
    mkdirSync(dirname(join(root, rel)), { recursive: true });
    writeFileSync(join(root, rel), text);
  };
  execFileSync("git", ["init", "-q"], { cwd: root });
  put("src/a.ts", "a();\n");
  put("src/b.ts", `// ${SPDX}\nb();\n`);
  put("src/c.css", "/* Generated by x. Do not edit. */\n");
  put("src/d.js", "// Copyright (c) 2020 Someone Else\nd();\n");
  put("src/untracked.ts", "u();\n");
  put("site/d.ts", "d();\n");
  execFileSync("git", ["add", "src/a.ts", "src/b.ts", "src/c.css", "src/d.js", "site/d.ts"], {
    cwd: root,
  });
  assert.deepEqual(
    plan(root).map(({ rel, action }) => [rel, action]),
    [
      ["src/a.ts", "add"],
      ["src/b.ts", "ok"],
      ["src/c.css", "generated"],
      ["src/d.js", UNLISTED],
    ],
  );
});
