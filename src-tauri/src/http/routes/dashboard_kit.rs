//! The dashboard kit every live doc gets: a stylesheet of tokens and `cs-`
//! components, and `window.codesense.kit` (icons, status badges, avatars, a DAG
//! layout). Served at stable paths under `/kit/v1/` and linked into each live
//! doc's head by [`kit_tags`], so a doc needs no boilerplate and frames share one
//! cached copy. The shipped avatar faces are served here too, for `kit.avatar`.

